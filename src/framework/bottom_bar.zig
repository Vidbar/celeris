//! BottomBar — reactive component migrated to the canonical pattern.
//!
//! Framework-owned via `ctx.mountOwned(BottomBar, .{ .items = &ITEMS, .on_select = ... })`:
//! no `init`/`register`/`deinit`/action-id in user code. Material's BottomAppBar
//! analogue: a horizontal row of N action items (icon stacked over an optional
//! label). Items have NO selected state — every item is a momentary action that
//! fires `on_select(context, index)` on click. The clicked/hovered item is
//! resolved by matching `ev.node_id` against the row ids captured at build time
//! (same pattern as Dropdown/Tabs — no per-index action-id strings).
//!
//! Per-item hover is a single Signal(index) driving a render-only white overlay
//! via a fine-grained effect: a hover never relayouts or rebuilds the subtree.
//!
//! Anchoring is the parent's job: drop this as the last child of a flex-column
//! layout (the same way Flutter hands it to Scaffold.bottomNavigationBar).

const std = @import("std");
const component = @import("component.zig");
const signals = @import("../core/signals.zig");
const events = @import("events.zig");
const props = @import("../core/properties.zig");
const reg = @import("../core/registry.zig");

const BuildContext = component.BuildContext;

/// Sentinel for "no item hovered".
const NONE: usize = std.math.maxInt(usize);

pub const BottomBarItem = struct {
    /// Glyph/icon string (rendered as text, like IconButton today).
    icon: []const u8,
    /// Caption shown under the icon. Pass "" for an icon-only item.
    label: []const u8 = "",
};

pub const BottomBar = struct {
    // Props (set from mountOwned's init_props; re-applied on rebuild).
    items: []const BottomBarItem = &.{},
    /// Fired on click with the index of the pressed item.
    on_select: ?*const fn (ctx: ?*anyopaque, index: usize) void = null,
    context: ?*anyopaque = null,

    // State (auto-created in onMount; preserved across rebuilds).
    hovered: signals.Signal(usize) = undefined,
    scope: signals.Scope = undefined,
    /// Row node ids for the current build (index ↔ item); repopulated each build.
    item_ids: std.array_list.Managed(reg.NodeId) = undefined,

    // Captured during build().
    store: ?*props.PropertyStore = null,
    bound: bool = false,

    pub fn onMount(self: *BottomBar, allocator: std.mem.Allocator) void {
        self.hovered = signals.Signal(usize).init(allocator, NONE);
        self.scope = signals.Scope.init(allocator);
        self.item_ids = std.array_list.Managed(reg.NodeId).init(allocator);
    }

    /// Tears down reactive state on unmount. The framework owns and frees
    /// the instance itself.
    pub fn deinit(self: *BottomBar) void {
        self.scope.deinit();
        self.hovered.deinit();
        self.item_ids.deinit();
    }

    /// One handler for every item cell: resolves the index by matching the
    /// event's node against the captured row ids.
    fn onItem(self: *BottomBar, ev: events.Event) void {
        for (self.item_ids.items, 0..) |it, i| {
            if (it != ev.node_id) continue;
            if (std.mem.eql(u8, ev.name, "mouse_enter")) {
                self.hovered.set(i);
            } else if (std.mem.eql(u8, ev.name, "mouse_leave")) {
                if (self.hovered.peek() == i) self.hovered.set(NONE);
            } else if (std.mem.eql(u8, ev.name, "click")) {
                if (self.on_select) |cb| cb(self.context, i);
            }
            return;
        }
    }

    pub fn build(self: *BottomBar, ctx: *BuildContext) !void {
        const b = ctx.builder;
        self.store = b.store;
        self.item_ids.clearRetainingCapacity();

        const root = try b.openNodeKeyed(.box, null);
        try b.width(root, 100, .percent);
        try b.height(root, 56, .px);
        try b.flexRow(root);
        try b.alignItems(root, .center);
        try b.justifyContent(root, .space_around);
        try b.background(root, b.theme.bg_surface.r, b.theme.bg_surface.g, b.theme.bg_surface.b);
        try b.borderWidth(root, b.theme.border_width);
        try b.borderColorOf(root, b.theme.border_color);
        try b.role(root, "bottom_bar");

        for (self.items) |item| {
            const cell = try b.openNodeKeyed(.box, null);
            try self.item_ids.append(cell);
            try b.flexColumn(cell);
            try b.flexGrow(cell, 1);
            try b.height(cell, 100, .percent);
            try b.alignItems(cell, .center);
            try b.justifyContent(cell, .center);
            try b.gap(cell, 2);
            if (b.theme.radius_base > 0) try b.radius(cell, b.theme.radius_base);

            // Hit modifiers keep the autogenerated "n{id}" action-id (C-ABI channel
            // unchanged); dispatch goes through typed (node, kind) handlers.
            var idbuf: [16]u8 = undefined;
            const auto_id = std.fmt.bufPrint(&idbuf, "n{d}", .{cell}) catch "n";
            try b.clickable(cell, auto_id);
            try b.hoverable(cell, auto_id);
            if (ctx.router) |r| {
                try r.onNode(cell, .click, ctx.handler(self, onItem));
                try r.onNode(cell, .mouse_enter, ctx.handler(self, onItem));
                try r.onNode(cell, .mouse_leave, ctx.handler(self, onItem));
            }

            const icon = try b.addText(item.icon);
            try b.fontSize(icon, 20);
            try b.textColor(icon, b.theme.text.r, b.theme.text.g, b.theme.text.b);

            if (item.label.len > 0) {
                const lbl = try b.addText(item.label);
                try b.fontSize(lbl, 11);
                try b.textColor(lbl, b.theme.text.r, b.theme.text.g, b.theme.text.b);
            }
            b.close(); // cell
        }
        b.close(); // root

        // Overlay is a fine-grained render-only effect (created once, re-applied
        // untracked after a structural rebuild clears the nodes) — same as Button.
        try component.bindVisuals(self, &self.scope, &self.bound, updateVisuals);
    }

    /// Translucent white overlay on the hovered cell only.
    fn updateVisuals(self: *BottomBar) void {
        const store = self.store orelse return;
        const hov = self.hovered.get();
        for (self.item_ids.items, 0..) |node, i| {
            const a: f32 = if (i == hov) 25.0 / 255.0 else 0.0;
            store.setStyle(node, .background, .{ .color = .{ .r = 1, .g = 1, .b = 1, .a = a } }) catch {};
        }
    }
};

// ── Tests ─────────────────────────────────────────────────────────────────────

const testing = std.testing;

const ITEMS = [_]BottomBarItem{
    .{ .icon = "H", .label = "Home" },
    .{ .icon = "S", .label = "Search" },
    .{ .icon = "P", .label = "Profile" },
};

fn mountBar(
    registry: *reg.UIRegistry,
    store: *props.PropertyStore,
    router: *events.EventRouter,
    mounts: *component.MountTable,
    init_props: anytype,
) !*BottomBar {
    var b = component.UIBuilder.init(registry, store);
    var ctx = BuildContext{ .builder = &b, .router = router, .mounts = mounts };
    _ = try b.openNodeKeyed(.box, null); // root
    try ctx.mountOwned(BottomBar, init_props);
    b.close();
    const anchor = registry.getNode(0).?.first_child;
    return @ptrCast(@alignCast(mounts.get(anchor).?.component_ptr));
}

test "BottomBar (mountOwned) hover raises a render-only overlay on the hovered item only" {
    const a = testing.allocator;
    var registry = reg.UIRegistry.init(a);
    defer registry.deinit();
    var store = props.PropertyStore.init(a);
    defer store.deinit();
    store.setRegistry(&registry);
    var router = events.EventRouter.init(a);
    defer router.deinit();
    var mounts = component.MountTable.init(a);
    defer mounts.deinit();
    registry.addNodeRemovedListener(&mounts, component.MountTable.nodeRemovedListener);

    const bar = try mountBar(&registry, &store, &router, &mounts, .{ .items = &ITEMS });
    try testing.expectEqual(@as(usize, 3), bar.item_ids.items.len);

    // Idle: every item transparent.
    for (bar.item_ids.items) |n| {
        try testing.expectApproxEqAbs(@as(f32, 0.0), store.getStyle(n, .background).?.color.a, 0.001);
    }

    for (registry.nodes.items) |*n| {
        n.layout_dirty = false;
        n.render_dirty = false;
    }

    _ = router.route(.{ .name = "mouse_enter", .id = "", .node_id = bar.item_ids.items[1] });
    try testing.expectApproxEqAbs(@as(f32, 25.0 / 255.0), store.getStyle(bar.item_ids.items[1], .background).?.color.a, 0.001);
    // Neighbours stay transparent, and the hover was render-only.
    try testing.expectApproxEqAbs(@as(f32, 0.0), store.getStyle(bar.item_ids.items[0], .background).?.color.a, 0.001);
    var any_layout = false;
    for (registry.nodes.items) |*n| {
        if (n.alive and n.layout_dirty) any_layout = true;
    }
    try testing.expect(!any_layout);

    _ = router.route(.{ .name = "mouse_leave", .id = "", .node_id = bar.item_ids.items[1] });
    try testing.expectApproxEqAbs(@as(f32, 0.0), store.getStyle(bar.item_ids.items[1], .background).?.color.a, 0.001);
}

test "BottomBar click fires on_select with the item index" {
    const a = testing.allocator;
    var registry = reg.UIRegistry.init(a);
    defer registry.deinit();
    var store = props.PropertyStore.init(a);
    defer store.deinit();
    store.setRegistry(&registry);
    var router = events.EventRouter.init(a);
    defer router.deinit();
    var mounts = component.MountTable.init(a);
    defer mounts.deinit();
    registry.addNodeRemovedListener(&mounts, component.MountTable.nodeRemovedListener);

    const Sink = struct {
        var last: usize = NONE;
        fn onSelect(_: ?*anyopaque, index: usize) void {
            last = index;
        }
    };
    Sink.last = NONE;

    const bar = try mountBar(&registry, &store, &router, &mounts, .{
        .items = &ITEMS,
        .on_select = Sink.onSelect,
    });

    _ = router.route(.{ .name = "click", .id = "", .node_id = bar.item_ids.items[2] });
    try testing.expectEqual(@as(usize, 2), Sink.last);
}
