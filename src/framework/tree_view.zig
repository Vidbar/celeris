    defer registry.deinit();
    var store = props.PropertyStore.init(a);
    defer store.deinit();
    store.setRegistry(&registry);
    var router = events.EventRouter.init(a);
    defer router.deinit();

    var roots = std.array_list.Managed(TreeNode).init(a);
    defer {
        for (roots.items) |*n| deinitNode(n);
        roots.deinit();
    }
    var k: usize = 0;
    while (k < 200) : (k += 1) try roots.append(leaf(a, k, "row"));

    var scroll_offset = signals.Signal(f32).init(a, 0);
    defer scroll_offset.deinit();
    var mounts = component.MountTable.init(a);
    defer mounts.deinit();
    registry.addNodeRemovedListener(&mounts, component.MountTable.nodeRemovedListener);

    var b = component.UIBuilder.init(&registry, &store);
    var ctx = component.BuildContext{ .builder = &b, .router = &router, .mounts = &mounts };
    _ = try b.openNodeKeyed(.box, null); // root
    try ctx.mountOwned(TreeView, .{
        .roots = &roots,
        .scroll_offset = &scroll_offset,
        .viewport_height = 100,
    });
    b.close();
    const anchor = registry.getNode(0).?.first_child;
    const tv: *TreeView = @ptrCast(@alignCast(mounts.get(anchor).?.component_ptr));
    const id = tv.root_id;

    // ↓ twenty times: selection lands on flat row 19 (far below the initial window).
    var d: usize = 0;
    while (d < 20) : (d += 1) _ = router.route(.{ .name = "key_down", .id = "", .node_id = id, .key_code = events.Key.down.code() });
    try testing.expectEqual(@as(?usize, 19), tv.selectedNode());

    // Ensure-visible scrolled the shared offset, the window rebuilt around row 19,
    // and the selected row is now materialized (while the old top row is gone).
    try testing.expect(scroll_offset.peek() < 0);
    try testing.expect(hasRow(tv, 19));
    try testing.expect(!hasRow(tv, 0));
}
