//! TreeView — reactive component migrated to the canonical pattern.
//!
//! **Data is lifted to app state**: the caller owns the tree (`roots` slice-list,
//! node names, memory) and an optional `data_rev` Signal. The widget is
//! framework-owned via `ctx.mountOwned(TreeView, .{ .roots = &app.tree_roots,
//! .data_rev = &app.tree_rev })` and *reads* the data: repopulating the tree is
//! "mutate `roots`, bump `data_rev`" — the build-effect re-runs this widget's
//! build in isolation (keyed reconciliation reuses rows). Selection/hover survive
//! a data swap when the selected/hovered id still exists in the new `roots`; only
//! ids that disappeared are cleared (live-refreshed trees keep the user's pick).
//!
//! **Selection/hover are also lifted** (same pattern as `Tabs.active`): pass
//! `.selected`/`.hovered` as caller-owned `*Signal(?usize)` to observe or drive
//! them from app state (e.g. an "element picker" writing `selected`, or a detail
//! panel reacting to it). Omit them and the widget uses equivalent internal
//! signals — the tree still works standalone.
//!
//! Three kinds of state change:
//!   • hover / select  → render-only. An effect repaints only the rows whose
//!     selected/hovered membership changed (the outgoing/incoming rows), read from
//!     a `row_map` (tree id → row/name NodeIds) rebuilt on every build; a structural
//!     rebuild forces a one-time full repaint. It reads the selected/hovered Signals,
//!     so writing either (by a click or by the caller) re-runs it.
//!   • expand / collapse → structural but local: the click handler toggles the
//!     node then partial-rebuilds the tree body via `UIBuilder.rootAt` — no
//!     whole-tree rebuild. (`expanded` lives on the caller's TreeNode.) Every
//!     gesture also fires `on_expand`/`on_collapse`; with `controlled_expansion`
//!     the widget only fires them and the caller applies the change via `data_rev`.
//!   • data swap (caller) → bump `data_rev` → isolated re-run of build().
//!
//! **Virtualization** (active only when the scroll bridge from `ScrollView.offset`
//! is wired — `scroll_offset` set and `viewport_height > 0`): the widget flattens
//! the visible tree into `flat` (the complete depth-first order) but materializes
//! only the scroll window `[start, end)` into the DOM, bracketed by two spacers that
//! reserve the off-window extent (so the container ScrollView's scrollbar spans the
//! full `flat.len * row_height`). A memoized `start_sig` fires the window-rebuild effect
//! once per row boundary crossed. Keyboard nav and ensure-visible index `flat` (the
//! full list); `row_map` is the windowed subset. Without the scroll bridge the
//! widget materializes every visible row (standalone behavior, unchanged).
//!
//! Events are typed (node, kind) handlers: one handler for every row resolves
//! the tree node by matching `ev.node_id` against the row_map (no "node_5"
//! action-id strings; hit modifiers keep the autogenerated "n{id}" id so the
//! C-ABI channel is unchanged).

const std = @import("std");
const builder_mod = @import("builder.zig");
const component = @import("component.zig");
const signals = @import("../core/signals.zig");
const events = @import("events.zig");
const props = @import("../core/properties.zig");
const reg = @import("../core/registry.zig");
const theme_mod = @import("theme.zig");
const text_render = @import("../render/text.zig");

pub const TreeNodeType = enum { branch, leaf };

pub const TreeNode = struct {
    id: usize,
    name: []const u8,
    node_type: TreeNodeType,
    expanded: bool = false,

    decorator: ?[]const u8 = null,
    decorator_color: ?[3]u8 = null,
    icon: ?[]const u8 = null,
    /// This node's icon color (e.g. folders vs file types). Null falls back to
    /// the tree's `colors.icon`, then the theme (warning for branches, accent
    /// for leaves).
    icon_color: ?theme_mod.Color = null,

    children: std.array_list.Managed(TreeNode),
};

/// Delivers a widget-level event (`name` = "expand" / "collapse" / "activate") to a
/// caller `events.Handler`, with the tree node id in `Event.item_id` — the same
/// synthesized-event shape as `Dialog`'s "close".
fn fireItem(h: ?events.Handler, name: []const u8, node_id: usize) void {
    const handler = h orelse return;
    handler.call(handler.ptr, .{ .name = name, .id = "", .item_id = node_id });
}

const RowInfo = struct { node_id: usize, row: reg.NodeId, name: reg.NodeId, caret: reg.NodeId = reg.NULL_NODE };

/// One entry of the flattened visible order (a depth-first walk that expands only
/// `expanded` branches). It holds the *complete* visible list — keyboard nav and
/// ensure-visible index into it — while `row_map` holds only the materialized
/// (windowed) subset. `node` is borrowed from the caller's `roots`; it is re-derived
/// on every `buildBody`, so it stays valid between structural changes.
const FlatRow = struct { node: *TreeNode, depth: usize };

/// Rows kept above/below the viewport so a fast scroll doesn't flash blank before
/// the next window rebuild (same role as `VirtualList.overdraw`).
const OVERDRAW: usize = 4;

/// Width of the focused-row outline (a border always present on every row,
/// transparent unless focused — so it never shifts the row's content).
const FOCUS_OUTLINE_W: f32 = 1;

fn colorValue(c: theme_mod.Color) props.PropValue {
    return props.PropValue.rgbA(c.r, c.g, c.b, @as(f32, @floatFromInt(c.a)) / 255.0);
}

fn setColor(store: *props.PropertyStore, id: reg.NodeId, c: theme_mod.Color) !void {
    try store.setStyle(id, .color, colorValue(c));
}

/// Reconciliation keys for the window spacers, far above any realistic row count so
/// they never collide with the per-row keys (the absolute flat index).
const TOP_SPACER_KEY: u64 = std.math.maxInt(u64);
const BOTTOM_SPACER_KEY: u64 = std.math.maxInt(u64) - 1;

pub const TreeView = struct {
    // Props (set from mountOwned's init_props; re-applied on rebuild).
    /// Caller-owned tree data. The widget reads it (and toggles `expanded` on
    /// branch clicks unless `controlled_expansion`) but never allocates or frees nodes.
    roots: ?*std.array_list.Managed(TreeNode) = null,
    /// External, caller-owned revision signal: bump after swapping/mutating the
    /// tree data structurally — the widget's build re-runs (isolated) and stale
    /// selection/hover reset. Optional for static trees.
    data_rev: ?*signals.Signal(u32) = null,
    /// Optional caller-owned selection signal (two-way): the widget writes the
    /// clicked node's id and reads it to paint the highlight; the caller can also
    /// write it to drive selection (e.g. an element picker) and subscribe to react.
    /// Holds the selected node id, or null. Omit to use the internal signal.
    selected: ?*signals.Signal(?usize) = null,
    /// Optional caller-owned hover signal (two-way): the hovered node id on enter,
    /// null on leave. Lets the caller highlight the corresponding target elsewhere.
    /// Omit to use the internal signal.
    hovered: ?*signals.Signal(?usize) = null,
    /// Shared scroll offset with the container ScrollView (the *same* signal passed
    /// as `.offset` to that ScrollView). When provided together with a positive
    /// `viewport_height`, the widget nudges it to keep the selected row visible —
    /// the bridge for keyboard nav and the element-picker path (a caller
    /// `.selected.set(...)`). Omit for a tree that never needs to auto-scroll.
    scroll_offset: ?*signals.Signal(f32) = null,
    /// Visible viewport height in px (the same value passed as
    /// `ScrollView.viewport_height`). Ensure-visible is active only when this is
    /// `> 0` and `scroll_offset` is provided.
    viewport_height: f32 = 0,
    /// Whether clicking a branch row's body also toggles expand/collapse (the
    /// classic file-tree gesture, default). Set `false` for the DevTools/IDE
    /// pattern: a row click only selects; expanding is done via the caret (which
    /// is always clickable and toggles without touching the selection), keyboard
    /// ←/→, or Enter.
    toggle_on_row_click: bool = true,
    /// Disclosure glyph for an expanded branch. Defaults to a real down-pointing
    /// triangle (▾, U+25BE); override for a different look or if the loaded font
    /// lacks the triangle glyphs.
    caret_expanded: []const u8 = "▾",
    /// Disclosure glyph for a collapsed branch (▸, U+25B8 by default).
    caret_collapsed: []const u8 = "▸",
    /// Fired (event name "expand", branch id in `ev.item_id`) whenever a gesture
    /// asks to expand a branch: caret click, row click when `toggle_on_row_click`,
    /// →, Enter. Fires in both modes; uncontrolled, after the rows are rebuilt.
    on_expand: ?events.Handler = null,
    /// Fired (event name "collapse", branch id in `ev.item_id`) for the same
    /// gestures (← instead of →) when they ask to collapse a branch.
    on_collapse: ?events.Handler = null,
    /// Controlled expansion: when true the widget never writes `TreeNode.expanded`;
    /// it only fires `on_expand`/`on_collapse`. The caller updates `roots` (e.g.
    /// loading a branch's children lazily on first expand) and bumps `data_rev` —
    /// required in this mode, it is the only way the change reaches the widget.
    /// Selection/hover/scroll survive that rebuild like any data swap. False (the
    /// default) keeps the widget toggling `expanded` itself.
    controlled_expansion: bool = false,
    /// Fired (event name "activate", node id in `ev.item_id`) on a double click on
    /// a row and on Enter on a leaf (Enter on a branch keeps toggling). An IDE
    /// opens the file here. A double click on a branch row with
    /// `toggle_on_row_click` also toggles it twice (once per click), net unchanged.
    on_activate: ?events.Handler = null,
    /// Single-click activation (an IDE's "preview" open). When true, a single
    /// click on a leaf also fires `on_activate`, with event name "preview"; the
    /// double click and Enter keep firing it as "activate" (pin). The click that
    /// completes a double click does not fire a second "preview". Branch clicks
    /// keep toggling.
    activate_on_click: bool = false,
    /// Fired (event name "context_menu") on a right click and on Shift+F10 / the
    /// menu key. `ev.item_id` is the row's node id (null for a right click on
    /// empty space); `ev.x`/`ev.y` are window coordinates ready for
    /// `Menu.popupWindow` — the pointer for a click, the focused row's
    /// bottom-left for the keyboard. The row becomes the focused row (and the
    /// tree takes keyboard focus) before the handler runs; whether it is also
    /// selected is `context_menu_selects`.
    on_context_menu: ?events.Handler = null,
    /// Whether a right click also selects the row. False (the default) is the
    /// desktop-IDE behavior: the clicked row only gets the focus outline and the
    /// current selection stays. True: the row is selected first (file-manager style).
    context_menu_selects: bool = false,
    /// Reveal request (two-way, caller-owned): write a node id to scroll its row
    /// into view with the minimum scroll (a row already visible stays put); the
    /// widget writes null back once handled. The row must be visible in the tree:
    /// expand its ancestors first (with `controlled_expansion`, the caller does,
    /// then bumps `data_rev`). Needs the scroll bridge (`scroll_offset` +
    /// `viewport_height`); otherwise the request is consumed with no effect.
    reveal: ?*signals.Signal(?usize) = null,

    // ── Metrics (logical px) ──
    /// Row height. Raised to the label's line height when `font_size`/`text_style`
    /// would not fit, so a large font never clips.
    row_height: f32 = 22,
    /// Horizontal step per depth level.
    indent: f32 = 14,
    /// Row padding. `l` is the space before a top-level caret (depth adds
    /// `indent` per level), `r` the space after the label/decorator.
    /// The 1 px focus outline is drawn inside this padding, on each side whose
    /// padding is at least 1 px (a 0 side keeps its content flush, without outline).
    row_padding: component.EdgeInsets = .{ .t = 1, .r = 8, .b = 1, .l = 10 },
    /// Space between the icon and the label.
    icon_gap: f32 = 4,
    /// Row text style (label, caret, icon, decorator). Null = engine default text.
    text_style: ?theme_mod.TextStyle = null,
    /// Overrides only the size of `text_style` (or of the default text).
    font_size: ?f32 = null,
    /// Row colors; unset fields come from `theme.list`, then the base theme
    /// tokens (see `theme.ListColors`).
    colors: theme_mod.ListColors = .{},

    // State (auto-created in onMount; preserved across rebuilds). The internal
    // selection/hover signals are the fallback when the caller passes none.
    selected_state: signals.Signal(?usize) = undefined,
    hovered_state: signals.Signal(?usize) = undefined,
    scope: signals.Scope = undefined,
    row_map: std.array_list.Managed(RowInfo) = undefined,
    /// The full flattened visible order (see `FlatRow`). Rebuilt on every
    /// `buildBody`; `row_map` is the materialized subset of it.
    flat: std.array_list.Managed(FlatRow) = undefined,

    // Captured during build().
    store: ?*props.PropertyStore = null,
    router: ?*events.EventRouter = null,
    theme: @import("theme.zig").Theme = .{},
    root_id: reg.NodeId = reg.NULL_NODE,
    bound: bool = false,
    /// Last observed `data_rev` value; a change means the caller swapped the data,
    /// so selection/hover ids are re-validated against the new `roots`.
    last_data_rev: u32 = 0,

    // O(1) hover/selection repaint bookkeeping. `updateVisuals` normally repaints
    // only the ≤4 rows whose selected/hovered membership changed since the previous
    // run (tracked in `last_sel`/`last_hov`); a structural (re)build sets
    // `full_repaint` so every freshly-built row is painted once — keyed reuse keeps
    // stale backgrounds otherwise. `paint_visits` records how many rows the last run
    // touched (a test hook proving the loop is bounded, not O(rows)).
    last_sel: ?usize = null,
    last_hov: ?usize = null,
    full_repaint: bool = true,
    paint_visits: usize = 0,

    // Virtualization (active only when the scroll bridge is wired — `scroll_offset`
    // set and `viewport_height > 0`). `start_sig` memoizes the first materialized
    // flat index from `scroll_offset`, so the window-rebuild effect fires once per
    // row boundary crossed, not per scrolled pixel. `window_primed` guards the
    // effect's initial run: `buildBody` already materialized the window, so the
    // first run only needs to subscribe (a re-entrant DOM rebuild during build()
    // would reconcile against a tree that is still being assembled).
    start_sig: ?*signals.Computed(usize) = null,
    window_primed: bool = false,

    // Focus. `focus_state` is the keyboard cursor row (separate from the
    // selection: a right click moves it without selecting). It is only meaningful
    // while `sel_at_focus` still equals the selection: a selection change made
    // after the cursor moved (a click, the caller writing `selected`) carries the
    // cursor with it — see `focusedNode`. `has_focus` mirrors whether the tree
    // root holds keyboard focus (root focus/blur events); it switches the
    // selection colors to the inactive pair and hides the focus outline.
    focus_state: signals.Signal(?usize) = undefined,
    sel_at_focus: ?usize = null,
    has_focus: signals.Signal(bool) = undefined,
    last_foc: ?usize = null,
    last_has_focus: bool = false,
    reveal_bound: bool = false,
    /// True until the first visuals pass (which ensure-visibles an initial selection).
    never_painted: bool = true,
    /// Row palette resolved once per build / repaint pass (`theme.listColors`), and
    /// the icon override (`colors.icon` / `theme.list.icon`) that `buildNode` needs
    /// unresolved so the per-type default still applies.
    palette: theme_mod.ResolvedListColors = undefined,
    icon_override: ?theme_mod.Color = null,

    pub fn onMount(self: *TreeView, allocator: std.mem.Allocator) void {
        self.selected_state = signals.Signal(?usize).init(allocator, null);
        self.hovered_state = signals.Signal(?usize).init(allocator, null);
        self.focus_state = signals.Signal(?usize).init(allocator, null);
        self.has_focus = signals.Signal(bool).init(allocator, false);
        self.scope = signals.Scope.init(allocator);
        self.row_map = std.array_list.Managed(RowInfo).init(allocator);
        self.flat = std.array_list.Managed(FlatRow).init(allocator);
    }

    /// Tears down reactive state on unmount. `scope.deinit()` runs first so
    /// the visuals effect unsubscribes (from a caller-owned signal too) before the
    /// internal fallbacks are freed. The framework owns and frees the instance
    /// itself; the tree data belongs to the caller.
    pub fn deinit(self: *TreeView) void {
        self.scope.deinit();
        self.selected_state.deinit();
        self.hovered_state.deinit();
        self.focus_state.deinit();
        self.has_focus.deinit();
        self.row_map.deinit();
        self.flat.deinit();
    }

    /// The active selection signal: caller-owned if provided, else the internal one.
    fn selSig(self: *TreeView) *signals.Signal(?usize) {
        return self.selected orelse &self.selected_state;
    }
    /// The active hover signal: caller-owned if provided, else the internal one.
    fn hovSig(self: *TreeView) *signals.Signal(?usize) {
        return self.hovered orelse &self.hovered_state;
    }

    /// Currently selected node id (non-reactive read).
    pub fn selectedNode(self: *TreeView) ?usize {
        return self.selSig().peek();
    }
    /// Currently hovered node id (non-reactive read).
    pub fn hoveredNode(self: *TreeView) ?usize {
        return self.hovSig().peek();
    }

    /// The focused row (keyboard cursor), non-reactive: the row last focused by
    /// a right click or keyboard nav, unless the selection changed since — then
    /// the selected row.
    pub fn focusedNode(self: *TreeView) ?usize {
        return self.resolveFocus(self.selSig().peek(), self.focus_state.peek());
    }

    fn resolveFocus(self: *const TreeView, sel: ?usize, foc: ?usize) ?usize {
        if (foc != null and std.meta.eql(sel, self.sel_at_focus)) return foc;
        return sel;
    }

    /// Moves the focus cursor to `id` without touching the selection.
    fn setFocusRow(self: *TreeView, id: usize) void {
        self.sel_at_focus = self.selSig().peek();
        if (self.focus_state.peek() != id) self.focus_state.set(id);
    }

    /// Selects `id` and moves the focus cursor with it (click, keyboard nav).
    fn selectRow(self: *TreeView, id: usize) void {
        const sel = self.selSig();
        self.sel_at_focus = id;
        if (self.focus_state.peek() != id) self.focus_state.set(id);
        if (sel.peek() != id) sel.set(id);
    }

    /// The effective row height (see `row_height`).
    pub fn rowH(self: *const TreeView) f32 {
        const style = self.textStyle() orelse return self.row_height;
        const lh = if (style.line_height) |f| text_render.lineHeightWith(style.size, f) else text_render.lineHeight(style.size);
        return @max(self.row_height, @ceil(lh));
    }

    /// `text_style` with `font_size` applied, or null when neither is set.
    fn textStyle(self: *const TreeView) ?theme_mod.TextStyle {
        var style = self.text_style orelse (if (self.font_size != null) theme_mod.TextStyle{ .size = 0 } else return null);
        if (self.font_size) |s| style.size = s;
        if (style.size <= 0) return null;
        return style;
    }

    fn applyTextStyle(self: *const TreeView, b: *builder_mod.UIBuilder, id: reg.NodeId) !void {
        const style = self.textStyle() orelse return;
        try b.fontSize(id, style.size);
        if (style.line_height) |f| try b.lineHeight(id, f);
    }

    /// Recursively reports whether `id` exists anywhere in `list` (any depth,
    /// regardless of `expanded`) — used to preserve selection across data swaps.
    fn containsId(list: *std.array_list.Managed(TreeNode), id: usize) bool {
        for (list.items) |*node| {
            if (node.id == id) return true;
            if (containsId(&node.children, id)) return true;
        }
        return false;
    }

    /// Recursively finds the node with `id` anywhere in `list` (any depth), or
    /// null. Sibling of `containsId`, used by keyboard nav to inspect the selected
    /// node's type/expansion.
    fn findNode(list: *std.array_list.Managed(TreeNode), id: usize) ?*TreeNode {
        for (list.items) |*node| {
            if (node.id == id) return node;
            if (findNode(&node.children, id)) |n| return n;
        }
        return null;
    }

    /// Recursively finds the id of the parent of `id` in `list`, or null when `id`
    /// is a root (or absent). Used by ← to step out to the enclosing branch.
    fn findParentId(list: *std.array_list.Managed(TreeNode), id: usize) ?usize {
        for (list.items) |*node| {
            for (node.children.items) |*child| {
                if (child.id == id) return node.id;
            }
            if (findParentId(&node.children, id)) |p| return p;
        }
        return null;
    }

    /// Whether the widget windows its rows: only true when a scroll bridge is wired
    /// (a shared `scroll_offset` plus a positive `viewport_height`). Without it the
    /// widget can't know the visible range, so it materializes every visible row
    /// (the standalone behavior, unchanged).
    fn virtualized(self: *const TreeView) bool {
        return self.scroll_offset != null and self.viewport_height > 0;
    }

    /// Number of rows materialized in the window: the visible count plus overdraw on
    /// both sides.
    fn windowLen(self: *const TreeView) usize {
        const vis: usize = @intFromFloat(@ceil(self.viewport_height / self.rowH()));
        return vis + 2 * OVERDRAW;
    }

    /// First materialized flat index for the current scroll (non-reactive), floored
    /// at 0. `scroll_offset` is `<= 0`, so `-off` is the distance scrolled from the
    /// top; the first visible row is `floor(-off / rowH)`.
    fn startIndex(self: *TreeView) usize {
        const off = (self.scroll_offset orelse return 0).peek(); // <= 0
        const first: i64 = @intFromFloat(@floor(-off / self.rowH()));
        const s = first - @as(i64, @intCast(OVERDRAW));
        return if (s < 0) 0 else @intCast(s);
    }

    /// Reactive twin of `startIndex` for the memoizing `start_sig` computed: reading
    /// `scroll_offset` with `.get()` subscribes the computed, so it re-publishes only
    /// when the window's first index actually changes (a boundary crossing).
    fn computeStart(self: *TreeView) usize {
        const off = (self.scroll_offset orelse return 0).get(); // <= 0
        const first: i64 = @intFromFloat(@floor(-off / self.rowH()));
        const s = first - @as(i64, @intCast(OVERDRAW));
        return if (s < 0) 0 else @intCast(s);
    }

    /// Rebuilds `flat` — the complete depth-first order of currently-visible rows
    /// (expanded branches only). No DOM is touched; this is the cheap walk that
    /// windowing and keyboard nav index into.
    fn flatten(self: *TreeView) void {
        self.flat.clearRetainingCapacity();
        if (self.roots) |list| {
            for (list.items) |*node| self.appendFlat(node, 0);
        }
    }

    fn appendFlat(self: *TreeView, node: *TreeNode, depth: usize) void {
        self.flat.append(.{ .node = node, .depth = depth }) catch return;
        if (node.node_type == .branch and node.expanded) {
            for (node.children.items) |*child| self.appendFlat(child, depth + 1);
        }
    }

    /// Adjusts the shared `scroll_offset` so the row for `id` sits inside the
    /// viewport. No-op when the scroll bridge isn't wired, or `id` isn't currently
    /// a visible row (an ancestor is collapsed) — it does not expand ancestors to reveal it.
    /// Offsets are `<= 0`; the visible window in content space is
    /// `[-off, -off + viewport_height]`. Uses peek+set only — reading
    /// `scroll_offset` with `.get()` from the visuals effect (its only caller)
    /// would subscribe the effect to the offset and form a cycle.
    fn ensureRowVisible(self: *TreeView, id: usize) void {
        const so = self.scroll_offset orelse return;
        if (self.viewport_height <= 0) return;
        // Index into the *full* flattened order (not the windowed `row_map`): a row
        // scrolled out of the window still has a well-defined position.
        const i: usize = blk: {
            for (self.flat.items, 0..) |fr, idx| {
                if (fr.node.id == id) break :blk idx;
            }
            return; // not a visible row (an ancestor is collapsed)
        };
        const row_top = @as(f32, @floatFromInt(i)) * self.rowH();
        const row_bottom = row_top + self.rowH();
        const off = so.peek(); // <= 0
        if (row_top < -off) {
            so.set(-row_top); // row is above the window → align its top
        } else if (row_bottom > -off + self.viewport_height) {
            so.set(-(row_bottom - self.viewport_height)); // below → align its bottom
        }
    }

    /// Keyboard navigation, delivered to the focused tree root (the engine
    /// routes arrows/Enter to the focused node's key_down):
    ///   ↑/↓  move the selection across the visible rows (paint order = row_map),
    ///        clamped at the ends; from no/hidden selection they pick the first row.
    ///   →    expands a collapsed branch (structural rebuild), else steps to its
    ///        first child.
    ///   ←    collapses an expanded branch (structural rebuild), else steps to the
    ///        parent.
    ///   Enter toggles/activates the selected node — same effect as a click.
    /// Selection is written via `peek`+`set` (never subscribes), so the visuals
    /// effect repaints without a rebuild; the mouse path is untouched.
    fn onKey(self: *TreeView, ev: events.Event) void {
        const list = self.roots orelse return;
        // ↑/↓ walk the *full* flattened order, so navigation reaches rows outside the
        // materialized window (ensure-visible then scrolls them in).
        const rows = self.flat.items;
        if (rows.len == 0) return;
        // Navigation starts from the focus cursor (see `focusedNode`), and moves
        // selection and cursor together.

        // Index of the current selection among the visible rows (null if there's
        // no selection or it isn't currently visible).
        const cur: ?usize = blk: {
            if (self.focusedNode()) |id| {
                for (rows, 0..) |fr, i| {
                    if (fr.node.id == id) break :blk i;
                }
            }
            break :blk null;
        };

        switch (events.Key.fromCode(ev.key_code) orelse return) {
            .up => { // ↑
                const i = cur orelse {
                    self.selectRow(rows[0].node.id);
                    return;
                };
                if (i > 0) self.selectRow(rows[i - 1].node.id);
            },
            .down => { // ↓
                const i = cur orelse {
                    self.selectRow(rows[0].node.id);
                    return;
                };
                if (i + 1 < rows.len) self.selectRow(rows[i + 1].node.id);
            },
            .right => { // → expand, or descend into the first child
                const id = self.focusedNode() orelse {
                    self.selectRow(rows[0].node.id);
                    return;
                };
                const node = findNode(list, id) orelse return;
                if (node.node_type != .branch) return;
                if (!node.expanded) {
                    self.requestExpansion(node, true);
                } else if (node.children.items.len > 0) {
                    self.selectRow(node.children.items[0].id);
                }
            },
            .left => { // ← collapse, or step out to the parent
                const id = self.focusedNode() orelse {
                    self.selectRow(rows[0].node.id);
                    return;
                };
                const node = findNode(list, id) orelse return;
                if (node.node_type == .branch and node.expanded) {
                    self.requestExpansion(node, false);
                } else if (findParentId(list, id)) |pid| {
                    self.selectRow(pid);
                }
            },
            .enter => { // Enter — explicit activation: always toggles a branch
                const id = self.focusedNode() orelse return;
                const node = findNode(list, id) orelse return;
                if (node.node_type == .leaf) {
                    fireItem(self.on_activate, "activate", id);
                } else self.toggleNode(node);
            },
            .apps => self.keyboardContextMenu(),
            .f10 => if (ev.shift) self.keyboardContextMenu(),
            else => {},
        }
    }

    /// Shift+F10 / menu key: the context menu of the focused row, anchored at the
    /// row's bottom-left (window coordinates) — computed from the tree root's
    /// geometry and the row's flat index, so it holds for a row outside the
    /// materialized window too (ensure-visible scrolls it in first).
    fn keyboardContextMenu(self: *TreeView) void {
        const id = self.focusedNode() orelse return;
        const i: usize = blk: {
            for (self.flat.items, 0..) |fr, idx| {
                if (fr.node.id == id) break :blk idx;
            }
            return;
        };
        // Ensure-visible only writes the offset; the layout is solved next frame, so
        // the root's geometry is still pre-scroll. Apply the scroll delta here.
        const off_before: f32 = if (self.scroll_offset) |so| so.peek() else 0;
        self.ensureRowVisible(id);
        const off_after: f32 = if (self.scroll_offset) |so| so.peek() else 0;
        var x: f32 = 0;
        var y: f32 = off_after - off_before;
        if (self.store) |st| if (st.registry) |rg| if (rg.getNode(self.root_id)) |n| {
            x = n.geometry.x;
            y += n.geometry.y;
        };
        const depth: f32 = @floatFromInt(self.flat.items[i].depth);
        x += self.row_padding.l + depth * self.indent;
        y += @as(f32, @floatFromInt(i + 1)) * self.rowH();
        self.fireContextMenu(id, x, y);
    }

    fn fireContextMenu(self: *TreeView, id: ?usize, x: f32, y: f32) void {
        const h = self.on_context_menu orelse return;
        h.call(h.ptr, .{ .name = "context_menu", .id = "", .item_id = id, .x = x, .y = y });
    }

    /// Root-level events: keyboard focus in/out (switches the selection colors
    /// and the focus outline) and a right click that no row handled (empty space).
    fn onRootEvent(self: *TreeView, ev: events.Event) void {
        if (std.mem.eql(u8, ev.name, "focus")) {
            if (!self.has_focus.peek()) self.has_focus.set(true);
        } else if (std.mem.eql(u8, ev.name, "blur")) {
            if (self.has_focus.peek()) self.has_focus.set(false);
        } else if (std.mem.eql(u8, ev.name, "right_mouse_down")) {
            // The same event bubbles here after a row handled it: only a point
            // below the last row (from the solved geometry, no stored state) is
            // empty space.
            if (self.store) |st| if (st.registry) |rg| if (rg.getNode(self.root_id)) |n| {
                const rows_bottom = n.geometry.y + @as(f32, @floatFromInt(self.flat.items.len)) * self.rowH();
                if (ev.y < rows_bottom) return;
            };
            self.fireContextMenu(null, ev.x, ev.y);
        }
    }

    /// One typed handler for every row and caret (click + hover edges): resolves
    /// the tree node by matching the event's node against the row_map. A caret
    /// click only toggles (never selects); a row click selects and — by default
    /// (`toggle_on_row_click`) — also toggles a branch.
    fn onRowEvent(self: *TreeView, ev: events.Event) void {
        var on_caret = false;
        const id = blk: {
            for (self.row_map.items) |info| {
                if (info.row == ev.node_id) break :blk info.node_id;
                if (info.caret != reg.NULL_NODE and info.caret == ev.node_id) {
                    on_caret = true;
                    break :blk info.node_id;
                }
            }
            return;
        };
        if (std.mem.eql(u8, ev.name, "click")) {
            const list = self.roots orelse return;
            const node = findNode(list, id) orelse return;
            if (on_caret) {
                self.toggleNode(node); // disclosure gesture: no selection change
                return;
            }
            // Writing the selection signal re-runs the visuals effect; a toggled
            // branch also needs a structural rebuild for the new rows.
            self.selectRow(id);
            if (node.node_type == .branch) {
                if (self.toggle_on_row_click) self.toggleNode(node);
            } else if (self.activate_on_click and ev.key_code <= 1) {
                // key_code is the click count: the 2nd click of a double click was
                // already answered by double_click ("activate").
                fireItem(self.on_activate, "preview", id);
            }
        } else if (std.mem.eql(u8, ev.name, "right_mouse_down")) {
            if (self.context_menu_selects) self.selectRow(id) else self.setFocusRow(id);
            self.fireContextMenu(id, ev.x, ev.y);
        } else if (std.mem.eql(u8, ev.name, "double_click")) {
            if (on_caret) return; // rapid caret clicks are disclosure, not activation
            fireItem(self.on_activate, "activate", id);
        } else if (std.mem.eql(u8, ev.name, "mouse_enter")) {
            const hov = self.hovSig();
            if (hov.peek() == null or hov.peek().? != id) hov.set(id);
        } else if (std.mem.eql(u8, ev.name, "mouse_leave")) {
            const hov = self.hovSig();
            if (hov.peek() != null and hov.peek().? == id) hov.set(null);
        }
    }

    fn rowHandler(self: *TreeView) events.Handler {
        const Wrap = struct {
            fn call(erased: ?*anyopaque, ev: events.Event) void {
                @as(*TreeView, @ptrCast(@alignCast(erased.?))).onRowEvent(ev);
            }
        };
        return .{ .ptr = self, .call = Wrap.call };
    }

    /// Requests the opposite expansion state of a branch. No-op on leaves.
    fn toggleNode(self: *TreeView, node: *TreeNode) void {
        if (node.node_type != .branch) return;
        self.requestExpansion(node, !node.expanded);
    }

    /// Single funnel for every expand/collapse gesture: in uncontrolled mode writes
    /// `expanded` and partial-rebuilds the body, then notifies the caller. In
    /// `controlled_expansion` mode it only notifies: the caller's handler owns the
    /// change and bumps `data_rev` (which may re-run build() synchronously), so
    /// `node` is not touched after the handler returns.
    fn requestExpansion(self: *TreeView, node: *TreeNode, expand: bool) void {
        const id = node.id;
        if (!self.controlled_expansion) {
            node.expanded = expand;
            self.rebuildBody();
        }
        if (expand) fireItem(self.on_expand, "expand", id) else fireItem(self.on_collapse, "collapse", id);
    }

    pub fn build(self: *TreeView, ctx: *component.BuildContext) !void {
        const b = ctx.builder;
        self.store = b.store;
        self.router = ctx.router;
        self.theme = b.theme;
        // Controlled expansion reaches the widget only through a `data_rev` bump;
        // without it every expand/collapse would be silently dropped.
        std.debug.assert(!self.controlled_expansion or self.data_rev != null);

        // Subscribe the build-effect to caller data swaps; a bump re-runs this
        // build in isolation. On a swap, keep selection/hover if their id still
        // exists in the new data (stable caller-provided ids) and clear only the
        // ones that vanished — `peek`/conditional `set` so build never subscribes
        // to selection changes (that would rebuild the whole tree on every click).
        if (self.data_rev) |dr| {
            const v = dr.get();
            if (v != self.last_data_rev) {
                self.last_data_rev = v;
                if (self.roots) |list| {
                    const sel = self.selSig();
                    if (sel.peek()) |id| {
                        if (!containsId(list, id)) sel.set(null);
                    }
                    const hov = self.hovSig();
                    if (hov.peek()) |id| {
                        if (!containsId(list, id)) hov.set(null);
                    }
                    // The focus cursor follows the same rule: a vanished row
                    // hands the cursor back to the selection.
                    if (self.focus_state.peek()) |id| {
                        if (!containsId(list, id)) self.focus_state.set(null);
                    }
                }
            }
        }

        const root = try b.openNodeKeyed(.box, null);
        self.root_id = root;
        try b.width(root, 100, .percent);
        try b.height(root, 100, .percent);
        try b.flexColumn(root);
        try b.background(root, b.theme.bg_input.r, b.theme.bg_input.g, b.theme.bg_input.b);

        // The root is focusable and owns key_down — arrows/Enter route to the
        // focused node, so keyboard nav lives here (not per row). The root isn't
        // clickable, so Enter reaches onKey instead of synthesizing a row click.
        var idbuf: [16]u8 = undefined;
        const aid = std.fmt.bufPrint(&idbuf, "n{d}", .{root}) catch "n";
        try b.focusable(root, aid);
        // Accessibility: the container is a "tree"; each row is a "treeitem" (see
        // buildNode). A UIA client / screen reader can then navigate the rows, read
        // their names, and hear expanded/selected state.
        try b.role(root, "tree");
        try b.rightClickable(root, aid);
        if (self.router) |r| {
            try r.onNode(root, .key_down, ctx.handler(self, onKey));
            const rh = ctx.handler(self, onRootEvent);
            try r.onNode(root, .focus, rh);
            try r.onNode(root, .blur, rh);
            try r.onNode(root, .right_click, rh);
        }

        try self.buildBody(b);

        b.close(); // root

        // Virtualization (created once, when the scroll bridge is wired): `start_sig`
        // memoizes the window's first flat index from `scroll_offset`, so the
        // window-rebuild effect fires once per row boundary crossed. Created before
        // the visuals effect so that an initial off-window selection — whose
        // ensure-visible fires during the visuals effect's first run — cascades to a
        // window rebuild in the same propagation.
        if (self.virtualized() and self.start_sig == null) {
            self.start_sig = try self.scope.createComputed(usize, self, computeStart);
            _ = try self.scope.createEffect(self, onScrollWindow);
        }

        // Row highlights are a fine-grained render-only effect (created once,
        // re-applied untracked after a structural rebuild) — same as Button.
        try component.bindVisuals(self, &self.scope, &self.bound, updateVisuals);

        // Reveal requests: an effect on the caller's signal (created once).
        if (self.reveal != null and !self.reveal_bound) {
            self.reveal_bound = true;
            _ = try self.scope.createEffect(self, onReveal);
        }
    }

    /// The reveal effect: scrolls the requested row into view (minimum scroll),
    /// then consumes the request by writing null back.
    fn onReveal(self: *TreeView) void {
        const sig = self.reveal orelse return;
        const id = sig.get() orelse return;
        const prev = signals.untrackedBegin();
        defer signals.untrackedEnd(prev);
        self.ensureRowVisible(id);
        sig.set(null);
    }

    /// Builds the visible rows into the currently-open root. Shared by the initial
    /// build and the partial rebuild on expand/collapse/scroll (which is why it takes
    /// a raw builder: the rebuild paths have no BuildContext). Always re-derives
    /// `flat` first; then either materializes the whole list (standalone) or only the
    /// scroll window (virtualized).
    pub fn buildBody(self: *TreeView, b: *builder_mod.UIBuilder) !void {
        self.row_map.clearRetainingCapacity();
        self.flatten();
        self.palette = self.theme.listColors(self.colors);
        self.icon_override = self.colors.icon orelse self.theme.list.icon;

        if (self.virtualized()) {
            try self.buildWindow(b);
        } else {
            for (self.flat.items) |fr| {
                try self.buildNode(b, fr.node, fr.depth, null);
            }
            // Trailing pad (matches the standalone layout the client already uses).
            const spacer = try b.openNodeKeyed(.box, null);
            try b.width(spacer, 100, .percent);
            try b.height(spacer, 100, .px);
            b.close();
        }

        // Rows were (re)built from scratch: the next visuals pass must paint all of
        // them (keyed reuse leaves stale backgrounds on recycled row nodes).
        self.full_repaint = true;
    }

    /// Materializes only `[start, end)` of `flat`, bracketed by two spacers whose
    /// heights reserve the off-window extent — so the total content height stays
    /// `flat.len * rowH()` and the container ScrollView's scrollbar is unaffected.
    /// Rows are keyed by their ABSOLUTE flat index, so a window shift reuses the rows
    /// that remain in range (identity-stable, mirrors `VirtualList`).
    fn buildWindow(self: *TreeView, b: *builder_mod.UIBuilder) !void {
        const count = self.flat.items.len;
        const win = self.windowLen();
        var start = if (self.start_sig) |ss| ss.peek() else self.startIndex();
        var end = start + win;
        if (end > count) end = count;
        // Keep the window full at the bottom rather than shrinking it.
        if (end == count and count > win) start = count - win;
        if (start > count) start = count;

        const top = try b.openNodeKeyed(.box, TOP_SPACER_KEY);
        try b.width(top, 100, .percent);
        try b.height(top, @as(f32, @floatFromInt(start)) * self.rowH(), .px);
        b.close();

        var i = start;
        while (i < end) : (i += 1) {
            const fr = self.flat.items[i];
            try self.buildNode(b, fr.node, fr.depth, @as(u64, i));
        }

        const bot = try b.openNodeKeyed(.box, BOTTOM_SPACER_KEY);
        try b.width(bot, 100, .percent);
        try b.height(bot, @as(f32, @floatFromInt(count - end)) * self.rowH(), .px);
        b.close();
    }

    fn buildNode(self: *TreeView, b: *builder_mod.UIBuilder, node: *TreeNode, depth: usize, key: ?u64) !void {
        const pad = self.row_padding;
        const indent_px = pad.l + @as(f32, @floatFromInt(depth)) * self.indent;
        const row = try b.openNodeKeyed(.box, key);
        try b.width(row, 100, .percent);
        try b.height(row, self.rowH(), .px);
        // The focus outline is a border that is always present (transparent
        // unless this is the focused row), carved out of the padding — so showing
        // it never moves the row's content (heights/widths are border-box). Each
        // side takes at most its own padding, so a 0 padding stays exactly 0 (that
        // side just has no outline).
        try b.borderTop(row, @min(FOCUS_OUTLINE_W, @max(0, pad.t)));
        try b.borderRight(row, @min(FOCUS_OUTLINE_W, @max(0, pad.r)));
        try b.borderBottom(row, @min(FOCUS_OUTLINE_W, @max(0, pad.b)));
        try b.borderLeft(row, @min(FOCUS_OUTLINE_W, @max(0, indent_px)));
        try b.borderColorAlpha(row, 0, 0, 0, 0);
        try b.padding(
            row,
            @max(0, pad.t - FOCUS_OUTLINE_W),
            @max(0, pad.r - FOCUS_OUTLINE_W),
            @max(0, pad.b - FOCUS_OUTLINE_W),
            @max(0, indent_px - FOCUS_OUTLINE_W),
        );
        try b.flexRow(row);
        try b.alignItems(row, .center);
        // Single-line rows: a label that doesn't fit is clipped at the row's
        // right edge instead of wrapping (and growing the row).
        try b.overflowHidden(row);

        // Accessibility: expose the row as a "treeitem" whose name is the node text
        // (an explicit aria-label so the chevron/icon glyphs preceding the name in
        // the subtree aren't mistaken for it). Branches carry expanded state; the
        // selected state is reflected onto the `.checked` flag by `paintRow`, which
        // the UIA SelectionItem provider reads as IsSelected.
        try b.role(row, "treeitem");
        try b.ariaLabel(row, node.name);
        if (node.node_type == .branch) try b.setExpanded(row, node.expanded);

        // Hit modifiers keep the autogenerated "n{id}" action-id (C-ABI channel
        // unchanged); dispatch goes through the typed (node, kind) handler.
        var idbuf: [16]u8 = undefined;
        const auto_id = std.fmt.bufPrint(&idbuf, "n{d}", .{row}) catch "n";
        try b.clickable(row, auto_id);
        try b.hoverable(row, auto_id);
        try b.rightClickable(row, auto_id);
        if (self.router) |r| {
            const h = self.rowHandler();
            try r.onNode(row, .click, h);
            try r.onNode(row, .double_click, h);
            try r.onNode(row, .mouse_enter, h);
            try r.onNode(row, .mouse_leave, h);
            try r.onNode(row, .right_click, h);
        }

        // Chevron. On branches it is its own hit-target: clicking it toggles
        // expand/collapse without touching the selection (disclosure gesture),
        // regardless of `toggle_on_row_click`.
        const chevron_str = if (node.node_type == .branch)
            (if (node.expanded) self.caret_expanded else self.caret_collapsed)
        else
            "";
        const chevron = try b.addText(chevron_str);
        try b.width(chevron, 16, .px);
        try b.flexShrink(chevron, 0);
        try b.noWrap(chevron);
        try self.applyTextStyle(b, chevron);
        if (node.node_type == .branch) {
            var cidbuf: [16]u8 = undefined;
            const caret_id = std.fmt.bufPrint(&cidbuf, "n{d}", .{chevron}) catch "n";
            try b.clickable(chevron, caret_id);
            if (self.router) |r| try r.onNode(chevron, .click, self.rowHandler());
        } else {
            try b.pointerEventsNone(chevron);
        }
        try setColor(b.store, chevron, self.palette.caret);

        // Icon.
        const icon_str = if (node.icon) |i| i else "";
        const icon = try b.addText(icon_str);
        try b.width(icon, 16, .px);
        try b.flexShrink(icon, 0);
        try b.noWrap(icon);
        try self.applyTextStyle(b, icon);
        try b.pointerEventsNone(icon);
        const icon_c = node.icon_color orelse self.icon_override orelse
            (if (node.node_type == .branch) self.theme.warning else self.theme.accent);
        try setColor(b.store, icon, icon_c);

        // Name (selection color applied by the effect). One line, shrinkable to
        // zero (min-width 0) so the row's overflow clip cuts it at the right edge.
        const name_node = try b.addText(node.name);
        try b.flexGrow(name_node, 1);
        try b.flexShrink(name_node, 1);
        try b.minWidth(name_node, 0, .px);
        try b.noWrap(name_node);
        try b.marginLeft(name_node, self.icon_gap);
        try self.applyTextStyle(b, name_node);
        try b.pointerEventsNone(name_node);

        // Decorator (static color). Never shrinks: the label gives way first.
        if (node.decorator) |dec| {
            const dec_node = try b.addText(dec);
            try b.flexShrink(dec_node, 0);
            try b.noWrap(dec_node);
            try self.applyTextStyle(b, dec_node);
            try b.pointerEventsNone(dec_node);
            if (node.decorator_color) |color| {
                try setColor(b.store, dec_node, .{ .r = color[0], .g = color[1], .b = color[2] });
            }
        }

        b.close(); // row

        try self.row_map.append(.{
            .node_id = node.id,
            .row = row,
            .name = name_node,
            .caret = if (node.node_type == .branch) chevron else reg.NULL_NODE,
        });
        // No recursion: `flatten` already laid out children in visible order; every
        // row (windowed or not) is built from a single pass over `flat`.
    }

    /// Structural rebuild (expand/collapse, keyboard, data swap): re-derives `flat`,
    /// rebuilds the body DOM, and repaints + ensure-visibles via `updateVisuals`.
    fn rebuildBody(self: *TreeView) void {
        component.rebuildTreeBody(self);
    }

    /// DOM-only rebuild used by the scroll-window effect: same as `rebuildBody` minus
    /// `updateVisuals`, so a plain scroll re-materializes the window and paints the
    /// fresh rows WITHOUT running ensure-visible (which would snap back to the
    /// selection). `component.rebuildTreeBody` always calls `updateVisuals`, so the
    /// scroll path can't reuse it.
    fn rebuildWindowDom(self: *TreeView) void {
        const store = self.store orelse return;
        const registry = store.registry orelse return;
        if (self.root_id == reg.NULL_NODE) return;
        var b = builder_mod.UIBuilder.init(registry, store);
        b.theme = self.theme;
        b.rootAt(self.root_id) catch return;
        self.buildBody(&b) catch {};
        b.close();
        registry.markLayoutDirty(self.root_id);
    }

    /// The window-rebuild effect: subscribes to `start_sig` (fires once per row
    /// boundary crossed) and re-materializes the visible window. The first run only
    /// primes the subscription — `buildBody` already built the window and a
    /// re-entrant `rootAt` during `build()` would reconcile a half-assembled tree.
    fn onScrollWindow(self: *TreeView) void {
        if (self.start_sig) |ss| _ = ss.get(); // subscribe / re-subscribe
        if (!self.window_primed) {
            self.window_primed = true;
            return;
        }
        // Rebuild + paint outside tracking: the DOM walk reads `scroll_offset`
        // (peek) and `selected`/`hovered` (get), none of which this effect should
        // depend on — it depends only on `start_sig`.
        const prev = signals.untrackedBegin();
        defer signals.untrackedEnd(prev);
        self.rebuildWindowDom();
        self.paintRows();
    }

    /// Returns the materialized row for `id`, or null when it isn't currently in
    /// `row_map` (collapsed ancestor, or — once virtualized — outside the window).
    fn rowInfoFor(self: *TreeView, id: usize) ?RowInfo {
        for (self.row_map.items) |info| {
            if (info.node_id == id) return info;
        }
        return null;
    }

    /// The row state `paintRow` renders.
    const RowPaint = struct { selected: bool, hovered: bool, focused: bool, active: bool };

    /// Paints one row: background (selected > hovered > transparent; the
    /// selection uses the inactive pair while the tree lacks keyboard focus),
    /// label color, and the focus outline (the focused row, only while the tree
    /// has focus). Counts the visit so tests can assert the repaint stayed bounded.
    fn paintRow(self: *TreeView, info: RowInfo, st: RowPaint) void {
        const store = self.store orelse return;
        const c = self.palette;
        const bg: theme_mod.Color = if (st.selected)
            (if (st.active) c.selected_bg else c.inactive_selected_bg)
        else if (st.hovered)
            c.hover_bg
        else
            theme_mod.Color.transparent();
        store.setStyle(info.row, .background, colorValue(bg)) catch {};
        const name_c = if (st.selected) (if (st.active) c.selected_text else c.inactive_selected_text) else c.text;
        store.setStyle(info.name, .color, colorValue(name_c)) catch {};
        const outline = if (st.focused and st.active) c.focus_outline else theme_mod.Color.transparent();
        store.setStyle(info.row, .border_color, colorValue(outline)) catch {};
        // Accessibility: mirror selection onto the row's `.checked` flag — the UIA
        // SelectionItem provider derives IsSelected from it, and the property-change
        // funnel raises the corresponding a11y event.
        store.setModifier(info.row, .checked, .{ .boolean = st.selected }) catch {};
        self.paint_visits += 1;
    }

    /// Repaints the materialized rows for the current selection/hover/focus — the
    /// whole window after a structural (re)build (`full_repaint`), else only the
    /// ≤6 rows whose membership changed (plus the selected and focused rows when
    /// the tree gains/loses keyboard focus). Reads the state signals with `.get()`,
    /// so when run as the visuals effect it subscribes to them; the scroll-window
    /// effect calls it untracked (no subscription). Does NOT ensure-visible.
    fn paintRows(self: *TreeView) void {
        if (self.store == null) return;
        const sel = self.selSig().get(); // subscribe to selection changes
        const hov = self.hovSig().get(); // subscribe to hover changes
        const foc = self.resolveFocus(sel, self.focus_state.get());
        const active = self.has_focus.get();
        self.palette = self.theme.listColors(self.colors);
        self.paint_visits = 0;

        const state = struct {
            fn of(id: usize, s: ?usize, h: ?usize, f: ?usize, a: bool) RowPaint {
                return .{
                    .selected = s != null and s.? == id,
                    .hovered = h != null and h.? == id,
                    .focused = f != null and f.? == id,
                    .active = a,
                };
            }
        };

        if (self.full_repaint) {
            // Fresh rows after a structural (re)build: paint every one.
            for (self.row_map.items) |info| {
                self.paintRow(info, state.of(info.node_id, sel, hov, foc, active));
            }
            self.full_repaint = false;
        } else {
            // Steady state: only the rows whose selected/hovered/focused membership
            // changed need repainting; a focus-in/out also restyles the selected and
            // focused rows (inactive selection colors, outline).
            const ids = [_]?usize{
                self.last_sel, sel,
                self.last_hov, hov,
                self.last_foc, foc,
            };
            for (ids, 0..) |maybe_id, k| {
                const id = maybe_id orelse continue;
                // Skip an id already repainted earlier in this run.
                var dup = false;
                for (ids[0..k]) |prev| {
                    if (prev != null and prev.? == id) {
                        dup = true;
                        break;
                    }
                }
                if (dup) continue;
                if (self.rowInfoFor(id)) |info| {
                    self.paintRow(info, state.of(id, sel, hov, foc, active));
                }
            }
        }
        self.last_sel = sel;
        self.last_hov = hov;
        self.last_foc = foc;
        self.last_has_focus = active;
    }

    /// The visuals effect: repaint the affected rows, then keep the selection visible
    /// when the scroll bridge is wired. Ensure-visible writes `scroll_offset`
    /// (peek+set, never `.get`), which cascades — via `start_sig` — to the
    /// window-rebuild effect in the same propagation, materializing the row it
    /// scrolled into view.
    pub fn updateVisuals(self: *TreeView) void {
        const prev_sel = self.last_sel;
        const first = self.never_painted;
        self.never_painted = false;
        self.paintRows();
        // Ensure-visible only when the selection itself changed (or on the first
        // paint): a hover, focus-in/out or focus-row move must not scroll the tree
        // back to the selection, undoing a user scroll or a `reveal`.
        if (self.scroll_offset != null and self.viewport_height > 0) {
            if (self.selSig().peek()) |id| {
                if (first or !std.meta.eql(prev_sel, @as(?usize, id))) self.ensureRowVisible(id);
            }
        }
    }
};

