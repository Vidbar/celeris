fn leaf(allocator: std.mem.Allocator, id: usize, name: []const u8) TreeNode {
    return .{ .id = id, .name = name, .node_type = .leaf, .children = std.array_list.Managed(TreeNode).init(allocator) };
}

fn branchNode(allocator: std.mem.Allocator, id: usize, name: []const u8, expanded: bool) TreeNode {
    return .{ .id = id, .name = name, .node_type = .branch, .expanded = expanded, .children = std.array_list.Managed(TreeNode).init(allocator) };
}

fn deinitNode(node: *TreeNode) void {
    for (node.children.items) |*child| deinitNode(child);
    node.children.deinit();
}

fn rowFor(tv: *TreeView, tree_id: usize) RowInfo {
    for (tv.row_map.items) |r| {
        if (r.node_id == tree_id) return r;
    }
    unreachable;
}

/// Whether `tree_id` is currently materialized (present in the windowed `row_map`).
fn hasRow(tv: *TreeView, tree_id: usize) bool {
    for (tv.row_map.items) |r| {
        if (r.node_id == tree_id) return true;
    }
    return false;
}

/// Sum of the direct children heights of `parent` (rows + spacers) — the reserved
/// content extent the container ScrollView scrolls over.
fn sumChildHeights(store: *props.PropertyStore, registry: *reg.UIRegistry, parent: reg.NodeId) f32 {
    var total: f32 = 0;
    var cur = registry.getNode(parent).?.first_child;
    while (cur != reg.NULL_NODE) : (cur = registry.getNode(cur).?.next_sibling) {
        if (store.getLayout(cur, .height)) |h| total += h.dimension.value;
    }
    return total;
}

