    // the resize path matches the win32 (physical-in) contract.
    const sc: u32 = @intCast(conn.buffer_scale);
    if (conn.resize_cb) |cb| cb(nativeHandle(win), win.width * sc, win.height * sc, @floatFromInt(conn.buffer_scale));
}
