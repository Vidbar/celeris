    defer std.posix.munmap(map);
    if (conn.xkb_ctx == null) return;
    const keymap = c.xkb_keymap_new_from_string(conn.xkb_ctx, @ptrCast(map.ptr), c.XKB_KEYMAP_FORMAT_TEXT_V1, c.XKB_KEYMAP_COMPILE_NO_FLAGS) orelse return;
    const state = c.xkb_state_new(keymap) orelse {
        c.xkb_keymap_unref(keymap);
        return;
    };
    if (conn.xkb_state) |old| c.xkb_state_unref(old);
    if (conn.xkb_keymap) |old| c.xkb_keymap_unref(old);
    conn.xkb_keymap = keymap;
    conn.xkb_state = state;
}
