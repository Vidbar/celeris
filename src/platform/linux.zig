fn kKeymap(data: ?*anyopaque, kb: ?*c.wl_keyboard, format: u32, fd: i32, size: u32) callconv(.c) void {
    _ = data;
    _ = kb;
    defer _ = std.os.linux.close(fd); // std.posix.close removed in Zig 0.16
    if (format != c.WL_KEYBOARD_KEYMAP_FORMAT_XKB_V1) return;
