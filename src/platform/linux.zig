/// Connects to the compositor and binds globals. Idempotent: a no-op once the
/// connection exists, so the 2nd+ window reuses it.
fn ensureConnection() !void {
    if (conn.display != null) return;

    // wl_display_connect uses $XDG_RUNTIME_DIR/$WAYLAND_DISPLAY. (Under WSLg that
    // must be /mnt/wslg/runtime-dir; the /run/user/N symlink isn't connectable.)
    conn.display = c.wl_display_connect(null) orelse {
        log.warn("wayland: wl_display_connect failed (check WAYLAND_DISPLAY / XDG_RUNTIME_DIR)\n", .{});
        return error.NoWaylandDisplay;
    };
    conn.registry = c.wl_display_get_registry(conn.display);
    _ = c.wl_registry_add_listener(conn.registry, &registry_listener, null);
    _ = c.wl_display_roundtrip(conn.display); // resolve globals (compositor, seat, output)
    if (conn.compositor == null) return error.NoWaylandCompositor;
    _ = c.wl_display_roundtrip(conn.display); // collect wl_output.scale for the bound output

    if (conn.data_mgr != null and conn.seat != null) {
        conn.data_device = c.wl_data_device_manager_get_data_device(conn.data_mgr, conn.seat);
        _ = c.wl_data_device_add_listener(conn.data_device, &data_device_listener, null);
    }

    // IME: one text-input object per seat (if the compositor supports v3).
    if (conn.text_input_mgr != null and conn.seat != null) {
        conn.text_input = c.zwp_text_input_manager_v3_get_text_input(conn.text_input_mgr, conn.seat);
        _ = c.zwp_text_input_v3_add_listener(conn.text_input, &text_input_listener, null);
    }

    conn.xkb_ctx = c.xkb_context_new(c.XKB_CONTEXT_NO_FLAGS);

    conn.decor = c.libdecor_new(conn.display, &decor_iface) orelse return error.LibdecorInitFailed;
}

pub fn initWindow(config: platform.WindowConfig) !platform.PlatformWindow {
    try ensureConnection();

    const win = try std.heap.page_allocator.create(Window);
    errdefer std.heap.page_allocator.destroy(win);
    win.* = .{ .width = config.width, .height = config.height };

    win.surface = c.wl_compositor_create_surface(conn.compositor) orelse return error.SurfaceCreateFailed;
    win.frame = c.libdecor_decorate(conn.decor, win.surface, &frame_iface, @ptrCast(win)) orelse return error.DecorateFailed;
    c.libdecor_frame_set_app_id(win.frame, "celeris");

    // NUL-terminate the title for the C API (titles are short → per-window buffer).
    const tn = @min(config.title.len, win.title_buf.len - 1);
    @memcpy(win.title_buf[0..tn], config.title[0..tn]);
    win.title_buf[tn] = 0;
    c.libdecor_frame_set_title(win.frame, @ptrCast(&win.title_buf));

    // Owner relationship: a child/dialog is parented to its owner's frame so the
    // compositor stacks/positions it correctly. (True modal input-blocking is
    // enforced engine-side in c_api via hasAliveModalChild.)
    if (config.parent) |ph| {
        if (parentWindowFor(ph)) |pw| {
            if (pw.frame) |pf| {
                win.parent = pw;
                c.libdecor_frame_set_parent(win.frame, pf);
            }
        }
    }

    registerWindow(win);
    c.libdecor_frame_map(win.frame);

    // Pump until the first configure so the content size is known before the
    // wgpu surface is created against it.
    var tries: u32 = 0;
    while (!win.configured and tries < 200) : (tries += 1) {
        _ = c.libdecor_dispatch(conn.decor, 20);
    }

    if (win.surface) |surf| c.wl_surface_set_buffer_scale(surf, conn.buffer_scale);

    return platform.PlatformWindow{
        .width = win.width,
        .height = win.height,
        .scale = @floatFromInt(conn.buffer_scale),
        .handle = nativeHandle(win),
        .ptr = win,
        .vtable = &vtable,
    };
}

/// Resolves a parent window from a native handle (matches by wl_surface).
fn parentWindowFor(handle: platform.NativeWindowHandle) ?*Window {
    return switch (handle) {
        .linux => |l| windowForSurface(@ptrCast(@alignCast(l.surface))),
        else => null,
    };
}

pub fn pollSystemEvents(ctx: ?*anyopaque, input_cb: ?platform.InputCallback) bool {
    conn.input_cb = input_cb;
    conn.input_ctx = ctx;
    if (conn.decor) |d| _ = c.libdecor_dispatch(d, 0); // non-blocking
    // The app keeps running while any window is open; quits when the last closes.
    return anyWindowOpen();
}

/// eventfd a worker writes to so `wake()` can interrupt an idle `waitEvents`
/// poll. -1 until first use.
var g_wake_fd: i32 = -1;

fn ensureWakeFd() i32 {
    if (@atomicLoad(i32, &g_wake_fd, .acquire) >= 0) return g_wake_fd;
    // EFD_NONBLOCK (0x800) | EFD_CLOEXEC (0x80000).
    const rc = std.os.linux.eventfd(0, 0x80800);
    if (std.os.linux.errno(rc) != .SUCCESS) return -1; // E.init removed in Zig 0.16
    @atomicStore(i32, &g_wake_fd, @intCast(rc), .release);
    return g_wake_fd;
}

/// Blocks until a Wayland event arrives, `wake()` is called, or `timeout_ms`
/// elapses. Falls back to a plain timeout if the display/fd isn't available.
pub fn waitEvents(timeout_ms: u32) void {
    const d = conn.display orelse {
        // std.Thread.sleep was removed in Zig 0.16; use the raw syscall like the rest of this file.
        const ts: std.os.linux.timespec = .{ .sec = @intCast(timeout_ms / 1000), .nsec = @intCast((timeout_ms % 1000) * std.time.ns_per_ms) };
        _ = std.os.linux.nanosleep(&ts, null);
        return;
    };
    _ = c.wl_display_flush(d);
    const wl_fd: i32 = c.wl_display_get_fd(d);
    const wfd = ensureWakeFd();
    var fds = [_]std.posix.pollfd{
        .{ .fd = wl_fd, .events = std.posix.POLL.IN, .revents = 0 },
        .{ .fd = wfd, .events = std.posix.POLL.IN, .revents = 0 },
    };
    // If the wake fd failed, poll only the display fd (count = 1).
    const n: usize = if (wfd >= 0) 2 else 1;
    _ = std.posix.poll(fds[0..n], @intCast(timeout_ms)) catch return;
    // Drain the wake fd so the next idle wait blocks again.
    if (n == 2 and (fds[1].revents & std.posix.POLL.IN) != 0) {
        var buf: u64 = 0;
        _ = std.posix.read(wfd, std.mem.asBytes(&buf)) catch {};
    }
}

/// Wakes an idle `waitEvents` from any thread (thread-safe). No-op before the
/// wake fd exists.
pub fn wake() void {
    const fd = @atomicLoad(i32, &g_wake_fd, .acquire);
    if (fd < 0) return;
    const one: u64 = 1;
    _ = std.os.linux.write(fd, std.mem.asBytes(&one), @sizeOf(u64)); // std.posix.write removed in Zig 0.16
}
