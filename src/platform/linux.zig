    /// Integer output (DPI) scale; the buffer is rendered at logical × this.
    buffer_scale: i32 = 1,
    decor: ?*c.libdecor = null,
    xkb_ctx: ?*c.xkb_context = null,
    xkb_keymap: ?*c.xkb_keymap = null,
