var conn: Conn = .{};

// ── Per-window state ──────────────────────────────────────────────────────────
const Window = struct {
    surface: ?*c.wl_surface = null,
    frame: ?*c.libdecor_frame = null,
    /// Owner window for a dialog/child (libdecor_frame_set_parent), null = top-level.
    parent: ?*Window = null,
    width: u32 = 800,
    height: u32 = 600,
    open: bool = true,
    configured: bool = false,
    ptr_x: f32 = 0,
    ptr_y: f32 = 0,
    title_buf: [256]u8 = undefined,
};

/// Live windows, for surface→window routing and last-window connection teardown.
var g_windows: [16]?*Window = .{null} ** 16;

fn registerWindow(win: *Window) void {
    for (&g_windows) |*slot| {
        if (slot.* == null) {
            slot.* = win;
            return;
        }
    }
}
fn unregisterWindow(win: *Window) void {
    for (&g_windows) |*slot| {
        if (slot.* == win) slot.* = null;
    }
}
fn windowForSurface(surf: ?*c.wl_surface) ?*Window {
    if (surf == null) return null;
    for (g_windows) |slot| {
        if (slot) |w| {
            if (w.surface == surf) return w;
        }
    }
    return null;
}
fn anyWindowOpen() bool {
    for (g_windows) |slot| {
        if (slot) |w| {
            if (w.open) return true;
        }
    }
    return false;
}

fn nativeHandle(win: *Window) platform.NativeWindowHandle {
    return .{ .linux = .{ .display = @ptrCast(conn.display), .surface = @ptrCast(win.surface) } };
}

/// Effective Shift/Ctrl/Alt from the keyboard's xkb state (all false until a
/// keymap arrives). Pointer events carry it so shift-click / shift-drag work.
fn xkbMods() struct { shift: bool, ctrl: bool, alt: bool } {
    const s = conn.xkb_state orelse return .{ .shift = false, .ctrl = false, .alt = false };
    return .{
        .shift = c.xkb_state_mod_name_is_active(s, c.XKB_MOD_NAME_SHIFT, c.XKB_STATE_MODS_EFFECTIVE) == 1,
        .ctrl = c.xkb_state_mod_name_is_active(s, c.XKB_MOD_NAME_CTRL, c.XKB_STATE_MODS_EFFECTIVE) == 1,
        .alt = c.xkb_state_mod_name_is_active(s, c.XKB_MOD_NAME_ALT, c.XKB_STATE_MODS_EFFECTIVE) == 1,
    };
}

fn emit(win: *Window, ev_type: platform.InputEventType, x: f32, y: f32, key_code: u32, scroll_delta: f32) void {
    if (conn.input_cb) |cb| {
        const m = xkbMods();
        cb(conn.input_ctx, .{
            .native_handle = nativeHandle(win),
            .event_type = ev_type,
            .x = x,
            .y = y,
            .key_code = key_code,
            .scroll_delta = scroll_delta,
            .shift_held = m.shift,
            .ctrl_held = m.ctrl,
            .alt_held = m.alt,
        });
    }
}

fn fixedToF32(v: c.wl_fixed_t) f32 {
    return @as(f32, @floatFromInt(v)) / 256.0;
}

// ── Registry ────────────────────────────────────────────────────────────────

fn registryGlobal(data: ?*anyopaque, reg: ?*c.wl_registry, name: u32, iface_c: [*c]const u8, version: u32) callconv(.c) void {
    _ = data;
    _ = version;
    const iface = std.mem.span(iface_c);
    if (std.mem.eql(u8, iface, "wl_compositor")) {
        conn.compositor = @ptrCast(@alignCast(c.wl_registry_bind(reg, name, &c.wl_compositor_interface, 4)));
    } else if (std.mem.eql(u8, iface, "wl_seat")) {
        conn.seat = @ptrCast(@alignCast(c.wl_registry_bind(reg, name, &c.wl_seat_interface, 5)));
        _ = c.wl_seat_add_listener(conn.seat, &seat_listener, null);
    } else if (std.mem.eql(u8, iface, "wl_shm")) {
        conn.shm = @ptrCast(@alignCast(c.wl_registry_bind(reg, name, &c.wl_shm_interface, 1)));
    } else if (std.mem.eql(u8, iface, "wl_output") and conn.output == null) {
        conn.output = @ptrCast(@alignCast(c.wl_registry_bind(reg, name, &c.wl_output_interface, 2)));
        _ = c.wl_output_add_listener(conn.output, &output_listener, null);
    } else if (std.mem.eql(u8, iface, "wl_data_device_manager")) {
        conn.data_mgr = @ptrCast(@alignCast(c.wl_registry_bind(reg, name, &c.wl_data_device_manager_interface, 3)));
    } else if (std.mem.eql(u8, iface, "zwp_text_input_manager_v3")) {
        conn.text_input_mgr = @ptrCast(@alignCast(c.wl_registry_bind(reg, name, &c.zwp_text_input_manager_v3_interface, 1)));
    }
}

// ── IME (zwp_text_input_v3) ───────────────────────────────────────────────────

fn copyCStr(dst: []u8, src: [*c]const u8) usize {
    if (src == null) return 0;
    const s = std.mem.span(src);
    const n = @min(s.len, dst.len);
    @memcpy(dst[0..n], s[0..n]);
    return n;
}

fn emitIme(ev_type: platform.InputEventType, text: []const u8) void {
    const win = conn.ime_window orelse conn.keyboard_focus orelse return;
    if (conn.input_cb) |cb| {
        cb(conn.input_ctx, .{ .native_handle = nativeHandle(win), .event_type = ev_type, .text = text });
    }
}

fn tiEnter(_: ?*anyopaque, _: ?*c.zwp_text_input_v3, surf: ?*c.wl_surface) callconv(.c) void {
    conn.ime_window = windowForSurface(surf);
}
fn tiLeave(_: ?*anyopaque, _: ?*c.zwp_text_input_v3, surf: ?*c.wl_surface) callconv(.c) void {
    if (conn.ime_window == windowForSurface(surf)) conn.ime_window = null;
}
fn tiPreedit(_: ?*anyopaque, _: ?*c.zwp_text_input_v3, text: [*c]const u8, _: i32, _: i32) callconv(.c) void {
    conn.preedit_len = copyCStr(&conn.preedit_buf, text);
}
fn tiCommit(_: ?*anyopaque, _: ?*c.zwp_text_input_v3, text: [*c]const u8) callconv(.c) void {
    conn.commit_len = copyCStr(&conn.commit_buf, text);
    conn.commit_pending = true;
}
fn tiDeleteSurrounding(_: ?*anyopaque, _: ?*c.zwp_text_input_v3, _: u32, _: u32) callconv(.c) void {
    // Not handled yet (surrounding-text deletion) — preedit/commit cover the
    // common case; revisit with full surrounding-text support.
}
fn tiDone(_: ?*anyopaque, _: ?*c.zwp_text_input_v3, _: u32) callconv(.c) void {
    // Double-buffered: flush the accumulated commit (if any) then the preedit, and
    // reset for the next cycle (an absent preedit_string this round means empty).
    if (conn.commit_pending) {
        emitIme(.ime_commit, conn.commit_buf[0..conn.commit_len]);
        conn.commit_pending = false;
        conn.commit_len = 0;
    }
    emitIme(.ime_preedit, conn.preedit_buf[0..conn.preedit_len]);
    conn.preedit_len = 0;
}
const text_input_listener = c.zwp_text_input_v3_listener{
    .enter = tiEnter,
    .leave = tiLeave,
    .preedit_string = tiPreedit,
    .commit_string = tiCommit,
    .delete_surrounding_text = tiDeleteSurrounding,
    .done = tiDone,
};

// ── Clipboard (wl_data_device) ──────────────────────────────────────────────
const MIME_UTF8 = "text/plain;charset=utf-8";
const MIME_PLAIN = "text/plain";
const MIME_URI = "text/uri-list";

// Incoming selection (paste): an offer is announced, its mime types arrive, then
// it becomes the selection.
fn doOffer(_: ?*anyopaque, offer: ?*c.wl_data_offer, mime_c: [*c]const u8) callconv(.c) void {
    _ = offer;
    const m = std.mem.span(mime_c);
    if (std.mem.eql(u8, m, MIME_UTF8)) conn.pending_has_utf8 = true else if (std.mem.eql(u8, m, MIME_PLAIN)) conn.pending_has_plain = true else if (std.mem.eql(u8, m, MIME_URI)) conn.pending_has_uri = true;
}
fn doSourceActions(_: ?*anyopaque, _: ?*c.wl_data_offer, _: u32) callconv(.c) void {}
fn doAction(_: ?*anyopaque, _: ?*c.wl_data_offer, _: u32) callconv(.c) void {}
const data_offer_listener = c.wl_data_offer_listener{
    .offer = doOffer,
    .source_actions = doSourceActions,
    .action = doAction,
};

fn ddDataOffer(_: ?*anyopaque, _: ?*c.wl_data_device, offer: ?*c.wl_data_offer) callconv(.c) void {
    conn.pending_has_utf8 = false;
    conn.pending_has_plain = false;
    conn.pending_has_uri = false;
    _ = c.wl_data_offer_add_listener(offer, &data_offer_listener, null);
}

/// Preferred drag mime given what the current offer advertises.
fn dndMime() [*:0]const u8 {
    return if (conn.pending_has_uri) MIME_URI else if (conn.pending_has_utf8) MIME_UTF8 else MIME_PLAIN;
}
fn ddSelection(_: ?*anyopaque, _: ?*c.wl_data_device, offer: ?*c.wl_data_offer) callconv(.c) void {
    if (conn.clip_offer) |old| {
        if (old != offer) c.wl_data_offer_destroy(old);
    }
    conn.clip_offer = offer;
    if (offer != null) {
        conn.clip_has_utf8 = conn.pending_has_utf8;
        conn.clip_has_plain = conn.pending_has_plain;
    }
}
fn ddEnter(_: ?*anyopaque, _: ?*c.wl_data_device, serial: u32, surf: ?*c.wl_surface, x: c.wl_fixed_t, y: c.wl_fixed_t, offer: ?*c.wl_data_offer) callconv(.c) void {
    conn.dnd_offer = offer;
    conn.dnd_window = windowForSurface(surf);
    const s: f32 = @floatFromInt(conn.buffer_scale);
    conn.dnd_x = fixedToF32(x) * s;
    conn.dnd_y = fixedToF32(y) * s;
    if (offer) |o| {
        c.wl_data_offer_accept(o, serial, dndMime());
        c.wl_data_offer_set_actions(o, 1, 1); // DND_ACTION_COPY
    }
}
fn ddLeave(_: ?*anyopaque, _: ?*c.wl_data_device) callconv(.c) void {
    conn.dnd_offer = null;
    conn.dnd_window = null;
}
fn ddMotion(_: ?*anyopaque, _: ?*c.wl_data_device, _: u32, x: c.wl_fixed_t, y: c.wl_fixed_t) callconv(.c) void {
    const s: f32 = @floatFromInt(conn.buffer_scale);
    conn.dnd_x = fixedToF32(x) * s;
    conn.dnd_y = fixedToF32(y) * s;
}
fn ddDrop(_: ?*anyopaque, _: ?*c.wl_data_device) callconv(.c) void {
    const offer = conn.dnd_offer orelse return;
    const win = conn.dnd_window orelse return;
    var fds: [2]i32 = undefined;
    if (std.os.linux.pipe2(&fds, .{}) != 0) return;
    c.wl_data_offer_receive(offer, dndMime(), fds[1]);
    _ = std.os.linux.close(fds[1]);
    if (conn.display) |d| _ = c.wl_display_roundtrip(d);
    var buf: [4096]u8 = undefined;
    var n: usize = 0;
    while (n < buf.len) {
        const r = std.os.linux.read(fds[0], buf[n..].ptr, buf.len - n);
        if (r == 0 or r > buf.len) break; // 0 = EOF; >len = errno-encoded error
        n += r;
    }
    _ = std.os.linux.close(fds[0]);
    c.wl_data_offer_finish(offer);
    c.wl_data_offer_destroy(offer);
    conn.dnd_offer = null;
    // Deliver the drop to the engine at the pointer position with the payload.
    if (conn.input_cb) |cb| {
        cb(conn.input_ctx, .{ .native_handle = nativeHandle(win), .event_type = .drop, .x = conn.dnd_x, .y = conn.dnd_y, .text = buf[0..n] });
    }
}
const data_device_listener = c.wl_data_device_listener{
    .data_offer = ddDataOffer,
    .enter = ddEnter,
    .leave = ddLeave,
    .motion = ddMotion,
    .drop = ddDrop,
    .selection = ddSelection,
};

// Outgoing selection (copy): our source serves the text when another app pastes.
fn dsSend(_: ?*anyopaque, _: ?*c.wl_data_source, _: [*c]const u8, fd: i32) callconv(.c) void {
    if (conn.clip_set_text) |t| _ = std.os.linux.write(fd, t.ptr, t.len);
    _ = std.os.linux.close(fd);
}
fn dsCancelled(_: ?*anyopaque, source: ?*c.wl_data_source) callconv(.c) void {
    if (conn.data_source == source) conn.data_source = null;
    c.wl_data_source_destroy(source);
    if (conn.clip_set_text) |t| {
        std.heap.page_allocator.free(t);
        conn.clip_set_text = null;
    }
}
fn dsTarget(_: ?*anyopaque, _: ?*c.wl_data_source, _: [*c]const u8) callconv(.c) void {}
fn dsDndDropPerformed(_: ?*anyopaque, _: ?*c.wl_data_source) callconv(.c) void {}
fn dsDndFinished(_: ?*anyopaque, _: ?*c.wl_data_source) callconv(.c) void {}
fn dsAction(_: ?*anyopaque, _: ?*c.wl_data_source, _: u32) callconv(.c) void {}
const data_source_listener = c.wl_data_source_listener{
    .target = dsTarget,
    .send = dsSend,
    .cancelled = dsCancelled,
    .dnd_drop_performed = dsDndDropPerformed,
    .dnd_finished = dsDndFinished,
    .action = dsAction,
};

