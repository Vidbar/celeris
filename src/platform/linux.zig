// ── Pointer ─────────────────────────────────────────────────────────────────

fn pEnter(data: ?*anyopaque, p: ?*c.wl_pointer, serial: u32, surf: ?*c.wl_surface, sx: c.wl_fixed_t, sy: c.wl_fixed_t) callconv(.c) void {
    _ = data;
    _ = p;
    conn.last_serial = serial;
    conn.pointer_enter_serial = serial; // wl_pointer.set_cursor must use this serial
    conn.pointer_focus = windowForSurface(surf);
    // Wayland pointer coords are surface-local (logical); scale to physical so the
    // engine's uniform "physical in, /scale -> logical" model holds across OSes.
    const s: f32 = @floatFromInt(conn.buffer_scale);
    if (conn.pointer_focus) |w| {
        w.ptr_x = fixedToF32(sx) * s;
        w.ptr_y = fixedToF32(sy) * s;
    }
}
fn pLeave(data: ?*anyopaque, p: ?*c.wl_pointer, serial: u32, surf: ?*c.wl_surface) callconv(.c) void {
    _ = data;
    _ = p;
    conn.last_serial = serial;
    const win = windowForSurface(surf);
    // Tell the engine the pointer left the window so it clears hover state
    // (Win32 parity: TrackMouseEvent → WM_MOUSELEAVE).
    if (win) |w| emit(w, .mouse_leave, w.ptr_x, w.ptr_y, 0, 0);
    if (conn.pointer_focus == win) conn.pointer_focus = null;
}
fn pMotion(data: ?*anyopaque, p: ?*c.wl_pointer, time: u32, sx: c.wl_fixed_t, sy: c.wl_fixed_t) callconv(.c) void {
    _ = data;
    _ = p;
    _ = time;
    const win = conn.pointer_focus orelse return;
    const s: f32 = @floatFromInt(conn.buffer_scale);
    win.ptr_x = fixedToF32(sx) * s;
    win.ptr_y = fixedToF32(sy) * s;
    emit(win, .mouse_move, win.ptr_x, win.ptr_y, 0, 0);
}
fn pButton(data: ?*anyopaque, p: ?*c.wl_pointer, serial: u32, time: u32, button: u32, state: u32) callconv(.c) void {
    // Mouse capture during drags: Wayland gives us this for free. While a button
    // is held the compositor keeps an implicit pointer grab on the focused surface —
    // motion outside the surface still arrives (pMotion), and wl_pointer.leave is not
    // sent until the button is released — so slider/sash/scrollbar drags that exit the
    // window keep updating with no extra work (unlike Win32, which needs SetCapture).
    _ = data;
    _ = p;
    _ = time;
    conn.last_serial = serial;
    if (button != 0x110) return; // BTN_LEFT only
    const win = conn.pointer_focus orelse return;
    if (state == c.WL_POINTER_BUTTON_STATE_PRESSED) {
        emit(win, .mouse_down, win.ptr_x, win.ptr_y, 0, 0);
    } else {
        emit(win, .mouse_up, win.ptr_x, win.ptr_y, 0, 0);
    }
}
fn pAxis(data: ?*anyopaque, p: ?*c.wl_pointer, time: u32, axis: u32, value: c.wl_fixed_t) callconv(.c) void {
    _ = data;
    _ = p;
    _ = time;
    const win = conn.pointer_focus orelse return;
    if (axis > 1) return;
    // Axis 0 = vertical (positive = down → invert: engine up = +, like
    // win32); axis 1 = horizontal (positive = right, matches the engine's dx
    // convention — no inversion). shift_held lets the engine apply the
    // Shift+wheel → horizontal convention. emit() has no dx/shift slots, so
    // call the input callback directly.
    const m = xkbMods();
    if (conn.input_cb) |cb| {
        cb(conn.input_ctx, .{
            .native_handle = nativeHandle(win),
            .event_type = .scroll,
            .x = win.ptr_x,
            .y = win.ptr_y,
