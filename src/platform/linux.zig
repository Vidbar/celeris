pub fn clipboardSetText(text: []const u8) bool {
    const mgr = conn.data_mgr orelse return false;
    const dd = conn.data_device orelse return false;
    const a = std.heap.page_allocator;
    if (conn.clip_set_text) |old| a.free(old);
    conn.clip_set_text = a.dupe(u8, text) catch {
        conn.clip_set_text = null;
        return false;
    };
    if (conn.data_source) |old| c.wl_data_source_destroy(old);
    const src = c.wl_data_device_manager_create_data_source(mgr) orelse return false;
    conn.data_source = src;
    _ = c.wl_data_source_add_listener(src, &data_source_listener, null);
    c.wl_data_source_offer(src, MIME_UTF8);
    c.wl_data_source_offer(src, MIME_PLAIN);
    c.wl_data_device_set_selection(dd, src, conn.last_serial);
    if (conn.display) |d| _ = c.wl_display_flush(d);
    return true;
}

pub fn clipboardGetText(allocator: std.mem.Allocator) ?[]u8 {
    const offer = conn.clip_offer orelse return null;
    const display = conn.display orelse return null;
    const mime: [*:0]const u8 = if (conn.clip_has_utf8) MIME_UTF8 else if (conn.clip_has_plain) MIME_PLAIN else return null;

    var fds: [2]i32 = undefined;
    if (std.os.linux.pipe2(&fds, .{}) != 0) return null;
    c.wl_data_offer_receive(offer, mime, fds[1]);
    _ = std.os.linux.close(fds[1]); // we only read; the compositor/source writes the other end
    _ = c.wl_display_roundtrip(display); // send the request; run our own send() if we own the selection

    var buf = std.array_list.Managed(u8).init(allocator);
    errdefer buf.deinit();
    var chunk: [4096]u8 = undefined;
    while (true) {
        const n = std.os.linux.read(fds[0], &chunk, chunk.len);
        if (n == 0 or n > chunk.len) break; // 0 = EOF; >len = errno-encoded error
        buf.appendSlice(chunk[0..n]) catch break;
    }
    _ = std.os.linux.close(fds[0]);
    if (buf.items.len == 0) {
        buf.deinit();
        return null;
    }
    return buf.toOwnedSlice() catch null;
}

/// Candidate cursor names per shape (freedesktop name first, X11 fallback) — themes
/// vary, so try a couple and use the first the theme provides.
fn cursorNames(cursor: platform.CursorType) []const [*:0]const u8 {
    return switch (cursor) {
        .default => &.{ "default", "left_ptr" },
        .pointer => &.{ "pointer", "hand2", "hand1" },
        .text => &.{ "text", "xterm" },
        .resize_ew => &.{ "ew-resize", "sb_h_double_arrow" },
        .resize_ns => &.{ "ns-resize", "sb_v_double_arrow" },
    };
}

/// Sets the pointer cursor via a wl_cursor_theme buffer. The theme + cursor
/// surface are created lazily on first use. No-op until a pointer + shm exist.
pub fn setCursor(cursor: platform.CursorType) void {
    const ptr = conn.pointer orelse return;
    const shm = conn.shm orelse return;
    const compositor = conn.compositor orelse return;

    if (conn.cursor_surface == null) conn.cursor_surface = c.wl_compositor_create_surface(compositor);
    const surf = conn.cursor_surface orelse return;
    if (conn.cursor_theme == null) conn.cursor_theme = c.wl_cursor_theme_load(null, 24, shm);
    const theme = conn.cursor_theme orelse return;

    var wc: ?*c.wl_cursor = null;
    for (cursorNames(cursor)) |n| {
        wc = c.wl_cursor_theme_get_cursor(theme, n);
        if (wc != null) break;
    }
    const cur = wc orelse return;
    if (cur.*.image_count == 0) return;
    const img = cur.*.images[0] orelse return;
    const buf = c.wl_cursor_image_get_buffer(img) orelse return;

    c.wl_pointer_set_cursor(ptr, conn.pointer_enter_serial, surf, @intCast(img.*.hotspot_x), @intCast(img.*.hotspot_y));
    c.wl_surface_attach(surf, buf, 0, 0);
    c.wl_surface_damage(surf, 0, 0, @intCast(img.*.width), @intCast(img.*.height));
    c.wl_surface_commit(surf);
}

