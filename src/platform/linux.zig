/// Tears down the shared Wayland connection — called only when the LAST window
/// closes, so the display/seat/etc. outlive individual windows.
/// Enables/disables IME for the focused seat. The engine calls this when focus
/// moves to/from an editable widget so the compositor only composes in text
/// fields. No-op if the compositor lacks zwp_text_input_v3.
pub fn setImeActive(active: bool) void {
    const ti = conn.text_input orelse return;
    if (active == conn.ime_active) return;
    conn.ime_active = active;
    if (active) c.zwp_text_input_v3_enable(ti) else c.zwp_text_input_v3_disable(ti);
    c.zwp_text_input_v3_commit(ti);
    if (conn.display) |d| _ = c.wl_display_flush(d);
}

fn teardownConn() void {
    if (conn.text_input) |t| c.zwp_text_input_v3_destroy(t);
    if (conn.text_input_mgr) |m| c.zwp_text_input_manager_v3_destroy(m);
    if (conn.decor) |d| c.libdecor_unref(d);
    if (conn.xkb_state) |s| c.xkb_state_unref(s);
    if (conn.xkb_keymap) |k| c.xkb_keymap_unref(k);
    if (conn.xkb_ctx) |x| c.xkb_context_unref(x);
    if (conn.cursor_theme) |t| c.wl_cursor_theme_destroy(t);
    if (conn.cursor_surface) |s| c.wl_surface_destroy(s);
    // Destroy Wayland proxies in reverse creation order before disconnecting,
    // so the connection teardown doesn't strand live child objects.
    if (conn.data_source) |s| c.wl_data_source_destroy(s);
    if (conn.clip_offer) |o| c.wl_data_offer_destroy(o);
    if (conn.data_device) |d| c.wl_data_device_destroy(d);
    if (conn.data_mgr) |m| c.wl_data_device_manager_destroy(m);
    if (conn.clip_set_text) |t| std.heap.page_allocator.free(t);
    if (conn.shm) |s| c.wl_shm_destroy(s);
    if (conn.pointer) |p| c.wl_pointer_destroy(p);
    if (conn.keyboard) |k| c.wl_keyboard_destroy(k);
    if (conn.seat) |s| c.wl_seat_destroy(s);
    if (conn.output) |o| c.wl_output_destroy(o);
    if (conn.compositor) |co| c.wl_compositor_destroy(co);
    if (conn.registry) |r| c.wl_registry_destroy(r);
    if (conn.display) |d| c.wl_display_disconnect(d);
    conn = .{};
}

fn winDeinit(ptr: *anyopaque) void {
    const win: *Window = @ptrCast(@alignCast(ptr));
    unregisterWindow(win);
    // Drop dangling focus pointers so a later event can't dereference freed memory.
    if (conn.pointer_focus == win) conn.pointer_focus = null;
    if (conn.keyboard_focus == win) conn.keyboard_focus = null;

    if (win.frame) |f| c.libdecor_frame_unref(f);
    if (win.surface) |s| c.wl_surface_destroy(s);

    // Last window out tears down the shared connection.
    var any = false;
    for (g_windows) |slot| {
        if (slot != null) any = true;
    }
    if (!any) teardownConn();

    std.heap.page_allocator.destroy(win);
}
