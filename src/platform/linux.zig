fn frameConfigure(frame: ?*c.libdecor_frame, config: ?*c.libdecor_configuration, data: ?*anyopaque) callconv(.c) void {
    const win = winFromData(data) orelse return;
    var w: c_int = 0;
    var h: c_int = 0;
    if (c.libdecor_configuration_get_content_size(config, frame, &w, &h) and w > 0 and h > 0) {
        win.width = @intCast(w);
        win.height = @intCast(h);
    }
    const st = c.libdecor_state_new(@intCast(win.width), @intCast(win.height));
    c.libdecor_frame_commit(frame, st, config);
    c.libdecor_state_free(st);
    win.configured = true;
