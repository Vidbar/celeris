    cursor_theme: ?*c.wl_cursor_theme = null,
    cursor_surface: ?*c.wl_surface = null,
    pointer_enter_serial: u32 = 0,
    last_serial: u32 = 0,

    /// The window currently under the pointer / holding keyboard focus, resolved
    /// from the wl_surface in enter events. Input is emitted for these.
    pointer_focus: ?*Window = null,
    keyboard_focus: ?*Window = null,

    input_cb: ?platform.InputCallback = null,
    input_ctx: ?*anyopaque = null,
    resize_cb: ?platform.ResizeCallback = null,

