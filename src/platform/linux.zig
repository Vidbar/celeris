//! Linux windowing backend — Wayland (libdecor for decorations + xdg-shell,
//! wayland-client for surfaces/input, xkbcommon for keyboard). X11 is not
//! supported by design.
//!
//! Multi-window model: connection-global state (display, seat, pointer,
//! keyboard, shm, clipboard, xkb, libdecor) lives in `conn`; each window has its
//! own `Window` (surface + frame + size). Wayland's C listeners are bare function
//! pointers, so events are routed to the right window two ways: libdecor frame
//! callbacks receive the `*Window` as user-data, and pointer/keyboard enter events
//! carry a `wl_surface` we match back to a window (`conn.pointer_focus` /
//! `conn.keyboard_focus`). The engine pumps events once per frame via
//! `pollSystemEvents` (non-blocking `libdecor_dispatch`); listeners translate
//! Wayland events into `platform.InputEvent`s using the same key codes the widgets
//! expect (ASCII codepoint for char_input; Windows-VK-style codes for key_down —
//! see vkFromSym — so TextInput/TextArea behave identically across platforms).

